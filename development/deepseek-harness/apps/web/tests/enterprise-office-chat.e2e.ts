it('restores saved contact files and caption after reload, then delivers the actual persisted bytes once', async () => {
  const scaffold = await launchWebScaffold({ profile: { packages: [] }, extraOverlayPath: join(REPO_ROOT, 'enterprise-workbench.patch.yml') })
  onTestFinished(() => scaffold.close())
  const browser = await chromium.launch()
  onTestFinished(() => browser.close())
  const page = await newEnglishPage(browser, 900)
  const console = watchConsole(page)
  onTestFailed(() => saveFailureShot(page, 'enterprise-office-file-draft-reload'))
  await page.goto(scaffold.authenticatedUrl, { waitUntil: 'load' })
  const nav = page.getByRole('navigation', { name: 'Workbench', exact: true })
  await nav.getByRole('button', { name: 'Contacts', exact: true }).click()
  await page.locator('[data-office-member="owner"]').getByRole('button', { name: 'Message', exact: true }).click()
  const chat = page.getByRole('dialog', { name: 'Employee chat', exact: true })
  const input = chat.getByRole('textbox', { name: 'Message; Enter to send, Shift+Enter for a new line', exact: true })
  const picker = chat.getByLabel('Choose chat files', { exact: true })
  await expect.poll(() => picker.isEnabled()).toBe(true)
  const bytes = Buffer.alloc(1024 * 1024 + 17, 61)
  Buffer.from('刷新后实际发送的文件\0\n').copy(bytes)
  await picker.setInputFiles({ name: '刷新恢复.bin', mimeType: 'application/octet-stream', buffer: bytes })
  await chat.getByRole('group', { name: 'File draft', exact: true }).getByText('Files saved', { exact: true }).waitFor()
  await input.fill('文件及说明一起恢复')
  await expect.poll(() => chat.getByRole('status').textContent()).toBe('Draft saved')
  expect(scaffold.ctx.office.chat('local' as OfficeMemberId, 'owner' as OfficeMemberId).messages).toEqual([])
  const reads = vi.spyOn(scaffold.ctx.office, 'downloadChatFileDraft')
  onTestFinished(() =>{  reads.mockRestore() })
  const before = console.warnings.length
  await page.reload({ waitUntil: 'load' })
  await nav.getByRole('button', { name: 'Contacts', exact: true }).click()
  await page.getByRole('button', { name: 'Chat history', exact: true }).click()
  await chat.getByRole('list', { name: 'Files to send', exact: true })
    .getByRole('button', { name: 'Remove file · 刷新恢复.bin', exact: true }).waitFor()
  await expect.poll(() => input.inputValue()).toBe('文件及说明一起恢复')
  expect(reads).not.toHaveBeenCalled()
  await chat.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(() => chat.getByRole('list', { name: 'Files to send', exact: true }).count(), { timeout: 10000 }).toBe(0)
  expect(reads).not.toHaveBeenCalled()
  const messages = scaffold.ctx.office.chat('local' as OfficeMemberId, 'owner' as OfficeMemberId).messages
  expect(messages).toHaveLength(1)
  expect(messages[0]?.text).toBe('文件及说明一起恢复')
  const download = page.waitForEvent('download')
  await chat.getByRole('button', { name: 'Download attachment · 刷新恢复.bin', exact: true }).click()
  const path = await (await download).path()
  if (!path) throw new Error('No persisted draft file was saved')
  expect(Buffer.compare(await readFile(path), bytes)).toBe(0)
  expect(scaffold.ctx.office.chatFileDrafts('local' as OfficeMemberId).drafts[0]?.files).toEqual([])
  acknowledgeReloadConnectionLoss(console, before)
  expect(console.pageErrors).toEqual([])
  expect(console.warnings).toEqual([])
})

it('retains failed file saves and resolves real competing windows only through keep or load choices', async () => {
  const scaffold = await launchWebScaffold({ profile: { packages: [] }, extraOverlayPath: join(REPO_ROOT, 'enterprise-workbench.patch.yml') })
  onTestFinished(() => scaffold.close())
  const browser = await chromium.launch()
  onTestFinished(() => browser.close())
  const first = await newEnglishPage(browser, 900)
  const second = await newEnglishPage(browser, 900)
  onTestFailed(() => saveFailureShot(first, 'enterprise-office-file-draft-conflict'))
  for (const page of [first, second]) {
    await page.goto(scaffold.authenticatedUrl, { waitUntil: 'load' })
    await page.getByRole('navigation', { name: 'Workbench', exact: true }).getByRole('button', { name: 'Contacts', exact: true }).click()
    await page.locator('[data-office-member="owner"]').getByRole('button', { name: 'Message', exact: true }).click()
  }
  const a = first.getByRole('dialog', { name: 'Employee chat', exact: true })
  const b = second.getByRole('dialog', { name: 'Employee chat', exact: true })
  const picker = a.getByLabel('Choose chat files', { exact: true })
  await expect.poll(() => picker.isEnabled()).toBe(true)
  const domain = scaffold.ctx.storageDomain.get('enterprise_office_chat_file_drafts')!
  const writes = vi.spyOn(domain.global, 'set').mockRejectedValueOnce(new Error('Expected private file draft write failure'))
  onTestFinished(() =>{  writes.mockRestore() })
  await picker.setInputFiles({ name: '原文件.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('original bytes') })
  await a.getByRole('button', { name: 'Retry saving files', exact: true }).click()
  await a.getByRole('group', { name: 'File draft', exact: true }).getByText('Files saved', { exact: true }).waitFor()
  writes.mockRestore()
  await b.getByRole('list', { name: 'Files to send', exact: true })
    .getByRole('button', { name: 'Remove file · 原文件.bin', exact: true }).waitFor()
  const original = scaffold.ctx.office.saveChatFileDraft.bind(scaffold.ctx.office)
  const saves = vi.spyOn(scaffold.ctx.office, 'saveChatFileDraft')
  onTestFinished(() =>{  saves.mockRestore() })
  const entered = Promise.withResolvers<undefined>()
  const release = Promise.withResolvers<undefined>()
  onTestFinished(() => { release.resolve(undefined) })
  saves.mockImplementationOnce(async (actor, input) => { entered.resolve(undefined); await release.promise; return original(actor, input) })
  await picker.setInputFiles({ name: '窗口A新增.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('local addition') })
  await entered.promise
  await b.getByLabel('Choose chat files', { exact: true }).setInputFiles({ name: '窗口B新增.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('other addition') })
  await expect.poll(() => scaffold.ctx.office.chatFileDrafts('local' as OfficeMemberId).drafts[0]?.revision).toBe(2)
  release.resolve(undefined)
  await a.getByRole('button', { name: 'Keep my files', exact: true }).click()
  await a.getByRole('group', { name: 'File draft', exact: true }).getByText('Files saved', { exact: true }).waitFor()
  expect(scaffold.ctx.office.chatFileDrafts('local' as OfficeMemberId).drafts[0]?.files.map(value => value.name)).toEqual(['原文件.bin', '窗口A新增.bin'])
  await expect.poll(() => b.getByRole('list', { name: 'Files to send', exact: true }).textContent()).toContain('窗口A新增.bin')
  const enteredAgain = Promise.withResolvers<undefined>()
  const releaseAgain = Promise.withResolvers<undefined>()
  onTestFinished(() => { releaseAgain.resolve(undefined) })
  saves.mockImplementationOnce(async (actor, input) => {
    enteredAgain.resolve(undefined)
    await releaseAgain.promise
    return original(actor, input)
  })
  await picker.setInputFiles({ name: '窗口A未保存.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('pending local file') })
  await enteredAgain.promise
  await b.getByRole('button', { name: 'Clear file draft', exact: true }).click()
  await expect.poll(() => scaffold.ctx.office.chatFileDrafts('local' as OfficeMemberId).drafts[0]?.revision).toBe(4)
  releaseAgain.resolve(undefined)
  await a.getByRole('button', { name: 'Load saved files', exact: true }).click()
  await expect.poll(() => a.getByRole('list', { name: 'Files to send', exact: true }).count()).toBe(0)
  expect(scaffold.ctx.office.chat('local' as OfficeMemberId, 'owner' as OfficeMemberId).messages).toEqual([])
})

