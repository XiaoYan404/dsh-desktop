it('prepends earlier history without moving its visible anchor and keeps incoming messages unread while scrolled away', async () => {
  const scaffold = await launchWebScaffold({ extraOverlayPath: join(REPO_ROOT, 'enterprise-workbench.patch.yml') })
  onTestFinished(() => scaffold.close())
  const local = 'local' as OfficeMemberId
  const owner = 'owner' as OfficeMemberId
  for (let index = 0; index < 105; index++) await scaffold.ctx.office.sendMessage(owner, { id: randomUUID() as OfficeMessageId, recipientId: local, text: `History ${index}` })
  const original = scaffold.ctx.office.chat(local, owner)
  const browser = await chromium.launch()
  onTestFinished(() => browser.close())
  const page = await newEnglishPage(browser, 900)
  const console = watchConsole(page)
  await page.goto(scaffold.authenticatedUrl, { waitUntil: 'load' })
  await page.getByRole('navigation', { name: 'Workbench', exact: true }).getByRole('button', { name: 'Contacts', exact: true }).click()
  await page.locator('[data-office-member="owner"]').getByRole('button', { name: 'Message', exact: true }).click()
  const chat = page.getByRole('dialog', { name: 'Employee chat', exact: true })
  const history = chat.getByRole('log', { name: 'Chat history', exact: true })
  await expect.poll(() => history.locator('article').count()).toBe(100)
  await expect.poll(() => scaffold.ctx.office.chat(local, owner).readThrough).toBe(original.messages.at(-1)!.sequence)
  await history.evaluate((element) => { element.scrollTop = 0 })
  await expect.poll(() => chat.getByRole('button', { name: 'Back to latest', exact: true }).isVisible()).toBe(true)
  const visibleAnchor = history.locator(`[data-office-message="${original.messages[0]!.id}"]`)
  const before = await visibleAnchor.boundingBox()
  expect(before).not.toBeNull()
  await chat.getByRole('button', { name: 'Load earlier messages', exact: true }).click()
  await expect.poll(() => history.locator('article').count()).toBe(105)
  const after = await visibleAnchor.boundingBox()
  expect(after).not.toBeNull()
  expect(Math.abs(after!.y - before!.y)).toBeLessThanOrEqual(2)
  const top = await history.evaluate(element => element.scrollTop)
  const incoming = await scaffold.ctx.office.sendMessage(owner, { id: randomUUID() as OfficeMessageId, recipientId: local, text: 'Incoming while reading earlier history' })
  await expect.poll(() => history.locator('article').count()).toBe(106)
  expect(await history.evaluate(element => element.scrollTop)).toBe(top)
  expect(scaffold.ctx.office.chat(local).threads[0]?.unread).toBe(1)
  await chat.getByRole('button', { name: 'Back to latest', exact: true }).click()
  await expect.poll(() => scaffold.ctx.office.chat(local, owner).readThrough).toBe(incoming.sequence)
  await expect.poll(() => history.evaluate(element => element.scrollHeight - element.scrollTop - element.clientHeight))
    .toBeLessThanOrEqual(24)
  expect(console.pageErrors).toEqual([])
  expect(console.warnings).toEqual([])
})

