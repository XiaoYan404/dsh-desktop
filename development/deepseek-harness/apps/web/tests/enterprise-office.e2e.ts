it('recovers a failed first fixed-identity read without clearing an already authorized employee form', async () => {
  const scaffold = await launchWebScaffold({ extraOverlayPath: join(REPO_ROOT, 'enterprise-workbench.patch.yml') })
  onTestFinished(() => scaffold.close())
  const entry = [...scaffold.ctx.loader.entries()].find(row => row.options.name === '@deepseek-ai/dsh-client-ui-office')!
  await scaffold.ctx.configEditor.edit(entry, current => ({ ...current, principalId: 'owner' }))
  await scaffold.ctx.loader.await()
  const controller = scaffold.ctx.get('officeController') as OfficeController
  const original = controller.connection.bind(controller)
  const failed = vi.spyOn(controller, 'connection').mockRejectedValue(new Error('Expected initial identity read interruption'))
  onTestFinished(() => { failed.mockRestore() })
  const browser = await chromium.launch()
  onTestFinished(() => browser.close())
  const page = await newEnglishPage(browser, 900)
  const console = watchConsole(page)
  const identityRequests: string[] = []
  page.on('request', (request) => {
    if (new URL(request.url()).pathname.endsWith('/office/connection')) identityRequests.push(request.method())
  })
  await page.goto(scaffold.authenticatedUrl, { waitUntil: 'load' })
  const nav = page.getByRole('navigation', { name: 'Workbench', exact: true })
  await nav.getByRole('button', { name: 'Team', exact: true }).click()
  await page.getByRole('button', { name: 'Add member', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Add member', exact: true })
  await dialog.getByLabel('Employee ID', { exact: true }).fill('recovered_startup')
  await dialog.getByLabel('Name', { exact: true }).fill('Retained after identity recovery')
  await page.evaluate(() => new Promise<void>(done => requestAnimationFrame(() => { requestAnimationFrame(() => { done() }) })))
  await expect.poll(() => failed.mock.calls.length).toBeGreaterThan(0)
  const initialReads = identityRequests.length
  const response = page.waitForResponse(result => new URL(result.url()).pathname.endsWith('/office/connection'))
  failed.mockImplementation(original)
  const [confirmed] = await Promise.all([
    response,
    expect.poll(() => identityRequests.length, { timeout: 10000 }).toBeGreaterThan(initialReads),
  ])
  await confirmed.finished()
  await page.evaluate(() => new Promise<void>(done => requestAnimationFrame(() => { requestAnimationFrame(() => { done() }) })))
  expect(await dialog.getByLabel('Name', { exact: true }).inputValue()).toBe('Retained after identity recovery')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.locator('[data-office-member="recovered_startup"]').waitFor()
  expect(scaffold.ctx.office.view('owner' as OfficeMemberId).managedMembers?.filter(member => member.id === 'recovered_startup'))
    .toHaveLength(1)
  expect(console.pageErrors).toEqual([])
  expect(console.warnings).toEqual([])
})

