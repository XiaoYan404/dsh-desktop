it('serves reviewed versions and recycle-bin requests through real Remote codecs while retaining the Drive page', async () => {
  const scaffold = await launchWebScaffold({ profile: { packages: [] }, extraOverlayPath: join(REPO_ROOT, 'enterprise-workbench.patch.yml') })
  onTestFinished(() => scaffold.close())
  const browser = await chromium.launch()
  onTestFinished(() => browser.close())
  const page = await newEnglishPage(browser, 900)
  const console = watchConsole(page)
  onTestFailed(() => saveFailureShot(page, 'enterprise-office-drive-version-api'))
  const local = 'local' as OfficeMemberId
  const call = async (method: string, args: Record<string, unknown> = {}): Promise<unknown> => {
    const response = await scaffold.hostFetch(`/api/office/${method}`, { method: 'POST', headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ type: 'client-request', rpcId: randomUUID(), method: `office/${method}`, payload: { args } }) })
    expect(response.status).toBe(200)
    return response.json()
  }
  const original = Buffer.from('RPC original bytes\n')
  expect(await call('uploadDriveFile', { input: { space: 'private', folderId: null, name: 'RPC version.txt', requestId: randomUUID(),
    mediaType: 'text/plain', byteLength: original.length, dataBase64: original.toString('base64') } }))
    .toMatchObject({ result: { ok: true, value: { ok: true } } })
  const file = scaffold.ctx.office.drive(local, { space: 'private', folderId: null, search: '' }).entries[0]!
  const old = await scaffold.ctx.office.driveFileInfo(local, file.id)
  await page.goto(scaffold.authenticatedUrl, { waitUntil: 'load' })
  await page.getByRole('navigation', { name: 'Workbench', exact: true }).getByRole('button', { name: 'Drive', exact: true }).click()
  const drive = page.getByRole('region', { name: 'Drive', exact: true })
  const row = drive.locator(`[data-drive-entry="${file.id}"]`)
  await row.waitFor()
  const bytes = Buffer.from('RPC replacement binary\0')
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  const input = { space: 'private', folderId: null, name: file.name, requestId: randomUUID(), mediaType: 'application/octet-stream',
    byteLength: bytes.length, sha256, target: { id: file.id, revision: file.revision } }
  expect(await call('beginDriveUpload', { input })).toMatchObject({ result: { ok: true, value: { ok: true, value: { target: input.target } } } })
  const ticket = (await scaffold.ctx.office.driveUploads(local)).find(value => value.requestId === input.requestId)!
  expect(await call('appendDriveUpload', { input: { uploadId: ticket.id, index: 0, sha256, dataBase64: bytes.toString('base64') } }))
    .toMatchObject({ result: { ok: true, value: { ok: true } } })
  expect(await call('completeDriveUpload', { id: ticket.id })).toMatchObject({ result: { ok: true,
    value: { ok: true, value: { status: 'completed', fileId: file.id } } } })
  expect(await call('driveHistory', { id: file.id })).toMatchObject({ result: { ok: true, value: { ok: true, value: {
    entry: { id: file.id, name: file.name }, versions: [{ current: true, mediaType: input.mediaType, sha256 },
      { current: false, versionId: old.versionId, mediaType: 'text/plain' }],
  } } } })
  expect(await call('driveVersionInfo', { id: file.id, versionId: old.versionId })).toMatchObject({ result: { ok: true,
    value: { ok: true, value: { versionId: old.versionId, mediaType: 'text/plain', sha256: old.sha256 } } } })
  expect(await call('downloadDriveRange', { input: { id: file.id, versionId: old.versionId, offset: 0, byteLength: original.length } }))
    .toMatchObject({ result: { ok: true, value: { ok: true, value: { dataBase64: original.toString('base64') } } } })
  const updated = scaffold.ctx.office.driveHistory(local, file.id).entry
  const trashResult = await call('changeDriveLifecycle', { input: { id: file.id, revision: updated.revision, action: 'trash' } })
  const trashed = scaffold.ctx.office.driveTrash(local).entries[0]!
  expect(trashResult).toMatchObject({ result: { ok: true, value: { ok: true, value: { id: file.id, deletedAt: trashed.deletedAt } } } })
  await drive.getByRole('button', { name: 'Refresh', exact: true }).click()
  await row.waitFor({ state: 'hidden' })
  expect(await call('driveTrash')).toMatchObject({ result: { ok: true, value: { ok: true,
    value: { meId: local, entries: [{ id: file.id, name: file.name }] } } } })
  expect(await call('driveVersionInfo', { id: file.id, versionId: old.versionId }))
    .toMatchObject({ result: { ok: true, value: { ok: false, code: 'not_found' } } })
  expect(await call('changeDriveLifecycle', { input: { id: file.id, revision: trashed.revision, action: 'restore' } }))
    .toMatchObject({ result: { ok: true, value: { ok: true, value: { id: file.id } } } })
  await drive.getByRole('button', { name: 'Refresh', exact: true }).click()
  await row.waitFor()
  expect(scaffold.ctx.office.driveHistory(local, file.id).versions).toHaveLength(2)
  expect(console.pageErrors).toEqual([])
  expect(console.warnings).toEqual([])
})

